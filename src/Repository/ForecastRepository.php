    public function findByPlace(Place $place) {
        $qb = $this->createQueryBuilder('m');
        $qb->where('m.place = :place')
            ->setParameter('place', $place)
            ->andWhere('m.date > :now')
            ->setParameter('now', date('Y-m-d'));

        $query = $qb->getQuery();
        $result = $query->getResult();
        return $result;
    }

